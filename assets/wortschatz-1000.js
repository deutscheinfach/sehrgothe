    function slug(s) {
        return String(s).toLowerCase()
            .replace(/ä/g, "ae").replace(/ö/g, "oe").replace(/ü/g, "ue").replace(/ß/g, "ss")
            .replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);
    }

    let cache = null;
    function days() {
        if (cache) return cache;
        const out = [];
        THEMES.forEach(function (t) {
            for (let i = 0; i < t.w.length; i += 10) {
                out.push({
                    n: out.length + 1,
                    theme: t.t,
                    ar: t.ar,
                    words: t.w.slice(i, i + 10).map(function (w) {
                        return { id: "d-" + slug(w[0]), de: w[0], ar: w[1] };
                    })
                });
            }
        });
        cache = out;
        return out;
    }
    function words() {
        return days().reduce(function (all, d) {
            return all.concat(d.words.map(function (w) { return Object.assign({ day: d.n, theme: d.theme }, w); }));
        }, []);
    }

